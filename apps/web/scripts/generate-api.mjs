import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const endpoint = process.env.OPENAPI_URL || 'http://127.0.0.1:5599/documentation/json';
const output = path.join(webDir, 'src/generated/api.d.ts');

// 通过运行中的后端文档端点生成前端 API 类型。
const result = spawnSync('pnpm', ['exec', 'openapi-typescript', endpoint, '-o', output], {
  cwd: webDir,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});
if (result.status !== 0) process.exit(result.status ?? 1);

// 生成器默认英文文件头替换为中文，保持新增注释口径统一。
const generated = fs.readFileSync(output, 'utf8');
fs.writeFileSync(output, generated.replace(
  '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to this file.\n */',
  '/**\n * 此文件由 openapi-typescript 自动生成，请勿直接修改。\n */',
));
